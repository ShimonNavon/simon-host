/**
 * The two offer landing pages — not rungs of the ladder, but ways in for two
 * specific audiences: web agencies overpaying for hosting (/agencies) and
 * founders who want an idea live in 30 days (/launch).
 *
 * Same law as services.ts: sections render from this data, copy is never a
 * JSX hunt. Prices here are only the published ones from services.ts.
 *
 * Two launch gates live in this file (tests enforce both):
 *   - CASE_STUDY_APPROVED — the agency case with real figures (accounts,
 *     old bill, new bill) is written out only once Simon approves it. Until
 *     then the story states no numbers at all: no counts, no percentages.
 *   - CAPACITY_PER_MONTH — the honest-scarcity number ("I take N agency
 *     migrations a month"). null = state it without a figure.
 */
export type OfferFaq = { q: string; a: string };
export type Magnet = { title: string; body: string };

export type Offer = {
  id: string;
  /** Route path segment: the page lives at `/${slug}`. */
  slug: string;
  name: string;
  /** Short label for header/footer nav. */
  navLabel: string;
  tagline: string;
  /** Who this page is for — the first thing on the page. */
  callout: string;
  heroLine: string;
  /** The proof paragraph. For agencies it's gated by CASE_STUDY_APPROVED. */
  story: string;
  /** What changes for you / what stays exactly as it is. */
  changes: string[];
  stays: string[];
  /** The two lead magnets, rendered as two cards. */
  magnets: [Magnet, Magnet];
  guarantee: string;
  /** Honest scarcity. For agencies it's gated by CAPACITY_PER_MONTH. */
  scarcity: string;
  faq: OfferFaq[];
  seo: { title: string; description: string };
  /** Optional per-page Open Graph image; falls back to the site default. */
  ogImage?: string;
  ogImageAlt: string;
  ctaLabel: string;
  /** The one explicit ask, printed above the CTA button. */
  ctaLine: string;
  /** Pre-filled WhatsApp text, distinct from every service's. */
  whatsapp: string;
};

/** Launch gate: Simon's written OK for the anonymized agency case. */
export const CASE_STUDY_APPROVED = false;

/** Launch gate: real monthly capacity for agency migrations; null = no figure. */
export const CAPACITY_PER_MONTH: number | null = null;

export function agencyStory(approved: boolean): string {
  if (approved) {
    return (
      "סוכנות ישראלית עם 85 חשבונות cPanel שילמה ₪12,000 בחודש על אחסון. " +
      "אצלי אותם אתרים עולים לה ₪600 בחודש — עם רווח לסוכנות, ובלי שאף לקוח שלה הרגיש במעבר. " +
      "אותם אתרים, אותם לקוחות, אותו wp-admin. את השם אני לא מפרסם; את החשבונית אני מראה בשיחה."
    );
  }
  return (
    "המעבר הזה לא תיאורטי: התהליך כבר רץ על אתרי לקוחות אמיתיים של סוכנות ישראלית " +
    "שיושבת על ריסלר cPanel — אותם אתרים, אותם לקוחות, אותו wp-admin, וחשבון אחסון קטן בהרבה. " +
    "את המספרים המדויקים אני מראה בשיחה, לא בדף."
  );
}

export function agencyScarcity(capacity: number | null): string {
  const tail =
    " זה מה שבן־אדם אחד יכול לעשות כמו שצריך — כל אתר עובר בידיים, לא בסקריפט שרץ בלילה. " +
    "כשהחודש מלא, אני אומר את זה כאן, ולא מבטיח תאריך שאני לא יכול לעמוד בו.";
  if (capacity === null) {
    return "אני לוקח מספר מצומצם של העברות סוכנות בחודש." + tail;
  }
  return `אני לוקח ${capacity} העברות סוכנות בחודש.` + tail;
}

